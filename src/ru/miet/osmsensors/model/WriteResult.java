package ru.miet.osmsensors.model;

/** Результат конкурентной записи показания в хранилище. */
public enum WriteResult {
    /** Датчика с таким id не было, он добавлен. */
    ADDED,
    /** Коллизия по id: запись новее сохранённой, датчик заменён. */
    UPDATED,
    /** Коллизия по id: пришедшее показание старее сохранённого, оно отброшено. */
    STALE_IGNORED,
    /** Нового датчика некуда добавить: хранилище заполнено. */
    STORAGE_FULL
}
